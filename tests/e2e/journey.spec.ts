import { test, expect } from '@playwright/test';
test('campaign journey, persistence and browser isolation', async ({ page, browser }) => {
  await page.goto('/');
  if (await page.locator('details.workspace-settings').getAttribute('open') === null) await page.getByText('Workspace & import',{exact:true}).click();
  await page.getByRole('button', { name: /Load sample venue/ }).click();
  await page.getByRole('button', { name: /Draft campaign/ }).click();
  await expect(page.getByRole('status').first()).toContainText('Draft ready');
  await page.getByRole('button', {name:'Review invitation',exact:true}).click();
  await expect(page.getByRole('region', {name:'Review and approve invitation',exact:true})).toBeFocused();
  await expect(page.getByRole('heading', {name:'Review and approve invitation',exact:true})).toBeInViewport();
  await page.getByRole('button', { name: 'Mark top recommendation sold out' }).click();
  await expect(page.getByRole('status').first()).toContainText('sold out');
  await page.getByText('Campaign preferences', {exact:true}).click();
  await page.getByRole('button', { name: 'Replan draft' }).click();
  await page.getByRole('button', { name: 'Approve draft' }).click();
  await expect(page.getByRole('status').first()).toContainText('Draft approved');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export campaign', exact: true }).click();
  expect((await download).suggestedFilename()).toBe('secondshow-campaign.csv');
  await page.screenshot({path:'docs/screenshots/campaign-desktop.png',fullPage:true});
  await page.getByText('Review audience & recipient previews', {exact:true}).click();
  await page.getByRole('button', { name: 'Preview', exact: true }).first().click();
  await expect(page.getByRole('heading', { name: 'Your next night out.' })).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'docs/screenshots/recipient-mobile.png',fullPage:true});
  await page.getByRole('button', {name:'Preview sample checkout ↗',exact:true}).first().click();
  await expect(page.getByRole('region',{name:'Simulated ticket page'})).toBeVisible();
  await page.getByRole('button', { name: 'Record sample second purchase', exact: true }).first().click();
  await page.setViewportSize({width:1280,height:720});
  await expect(page.getByRole('status').first()).toContainText('Sample second purchase recorded');
  await page.getByRole('button', { name: /Outcomes/ }).click();
  await page.getByTestId('advance-clock').click();
  await expect(page.getByRole('status').first()).toContainText('advanced 30 days');
  await page.reload();
  await page.getByRole('button', { name: /Outcomes/ }).click();
  await expect(page.getByText('fully observed 30-day repeat rate')).toBeVisible();
  const other = await browser.newContext();
  const otherPage = await other.newPage();
  await otherPage.goto('/');
  await expect(otherPage.getByRole('button', { name: /Draft campaign/ })).toHaveCount(0);
  if (await otherPage.locator('details.workspace-settings').getAttribute('open') === null) await otherPage.getByText('Workspace & import',{exact:true}).click();
  await otherPage.getByRole('button', { name: /Load sample venue/ }).click();
  if (await page.locator('details.workspace-settings').getAttribute('open') === null) await page.getByText('Workspace & import',{exact:true}).click();
  await page.getByRole('button', { name: 'Reset my demo' }).click();
  await expect(page.getByRole('status').first()).toContainText('workspace was reset');
  await otherPage.reload();
  await expect(otherPage.getByRole('button', { name: /Draft campaign/ })).toBeVisible();
  await other.close();
});

test('queue curation mirrors the selected buyer and requires renewed approval', async ({page}) => {
  await page.goto('/');
  if (await page.locator('details.workspace-settings').getAttribute('open') === null) await page.getByText('Workspace & import',{exact:true}).click();
  await page.getByRole('button',{name:/Load sample venue/}).click();
  await page.getByRole('button',{name:'Draft campaign',exact:true}).click();
  await page.getByLabel('Current buyer').selectOption('buyer-03');
  await expect(page.locator('.invitation-panel')).toContainText('buyer-03');
  const add = page.getByRole('button',{name:/^Add /}).first();
  const artist = (await add.getAttribute('aria-label'))!.slice(4);
  await add.focus();
  await page.keyboard.press('Enter');
  await expect(page.locator('.invitation-panel')).toContainText(artist);
  await page.getByRole('button',{name:`Move ${artist} first`,exact:true}).click();
  await expect(page.locator('.invitation-show h3').first()).toHaveText(artist);
  await expect(page.locator('.queue-context')).toContainText('operator curated');
  await page.getByRole('button',{name:'Review invitation',exact:true}).click();
  await page.getByRole('button',{name:'Approve draft',exact:true}).click();
  await expect(page.getByRole('button',{name:'Export campaign',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:`Remove ${artist}`,exact:true}).click();
  await expect(page.getByRole('button',{name:'Export campaign',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'Approve draft',exact:true}).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button',{name:'Export JSON package',exact:true}).click();
  const file = await (await download).path();
  const {readFile} = await import('node:fs/promises');
  const payload = JSON.parse(await readFile(file!, 'utf8'));
  expect(payload.messagesSent).toBe(false);
  const recipient = payload.recipients.find((r:{customerId:string})=>r.customerId==='buyer-03');
  expect(recipient.tasteMode).toBe('operator curated');
  expect(recipient.evidence).toBeNull();
  await page.getByText('Campaign preferences',{exact:true}).click();
  for (const width of [390,320]) {
    await page.setViewportSize({width,height:844});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await expect(page.getByLabel('Current buyer')).toBeVisible();
  }
});
